-- Para demonstração: acesso anônimo somente a SELECT e INSERT.
-- NÃO use para avisos sensíveis ou em produção sem autenticação.
create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  title text not null check (length(trim(title)) between 1 and 150),
  body text not null check (length(trim(body)) between 1 and 2000),
  created_at timestamptz not null default now()
);
alter table public.notifications enable row level security;
drop policy if exists "engcomp_read_demo" on public.notifications;
drop policy if exists "engcomp_insert_demo" on public.notifications;
create policy "engcomp_read_demo" on public.notifications
  for select to anon using (true);
create policy "engcomp_insert_demo" on public.notifications
  for insert to anon with check (true);
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname='supabase_realtime' and schemaname='public' and tablename='notifications'
  ) then
    alter publication supabase_realtime add table public.notifications;
  end if;
end $$;
